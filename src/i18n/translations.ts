export function detectBrowserLanguage(): Language {
  if (typeof window !== 'undefined' && window.navigator) {
    const lang = window.navigator.language || (window.navigator as any).userLanguage || '';
    if (lang.toLowerCase().startsWith('ja')) {
      return 'ja';
    }
  }
  return 'en';
}
